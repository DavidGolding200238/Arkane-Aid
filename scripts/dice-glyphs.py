"""Writes src/lib/dice/glyphs.ts: the outlines of the digits 0-9 from Asul Bold (the app's
headingBold font), so the 3D dice can build their numbers as flat geometry with no textures.
Run once from the repo root: python3 scripts/dice-glyphs.py (needs fontTools)."""
from fontTools.ttLib import TTFont
from fontTools.pens.recordingPen import RecordingPen
from fontTools.pens.basePen import decomposeQuadraticSegment

FONT = "node_modules/@expo-google-fonts/asul/700Bold/Asul_700Bold.ttf"
font = TTFont(FONT)
em = font["head"].unitsPerEm
cmap = font.getBestCmap()
gs = font.getGlyphSet()
os2 = font["OS/2"]
cap = getattr(os2, "sCapHeight", 0) or em * 0.7

def r(v):
    return round(v / em, 4)

out = []
for ch in "0123456789":
    name = cmap[ord(ch)]
    pen = RecordingPen()
    gs[name].draw(pen)
    cmds = []
    for op, pts in pen.value:
        if op == "moveTo":
            cmds.append(["M", r(pts[0][0]), r(pts[0][1])])
        elif op == "lineTo":
            cmds.append(["L", r(pts[0][0]), r(pts[0][1])])
        elif op == "qCurveTo":
            if pts[-1] is None:
                raise SystemExit("implied-on-curve closed contours are not handled")
            for c, p in decomposeQuadraticSegment(pts):
                cmds.append(["Q", r(c[0]), r(c[1]), r(p[0]), r(p[1])])
        elif op == "curveTo":
            raise SystemExit("cubic outlines are not handled")
        elif op in ("closePath", "endPath"):
            cmds.append(["Z"])
    flat = []
    for c in cmds:
        flat.append(c[0])
        flat.extend(c[1:])
    path = " ".join(str(x) for x in flat)
    out.append(f'  "{ch}": {{ advance: {r(gs[name].width)}, path: "{path}" }},')

with open("src/lib/dice/glyphs.ts", "w") as f:
    f.write("// Generated by scripts/dice-glyphs.py from Asul Bold. Do not edit by hand.\n")
    f.write("// Units are ems, y up. Commands: M x y, L x y, Q cx cy x y, Z.\n")
    f.write(f"export const GLYPH_CAP_HEIGHT = {r(cap)};\n\n")
    f.write("export const GLYPHS: Record<string, { advance: number; path: string }> = {\n")
    f.write("\n".join(out) + "\n};\n")
print("ok")
